# arithmetic operators

a=4
b=3
c=a+b
print(c)

# assignment operators

d=34-23
print(d)

d+=3 # this is same as d=d+3
print(d)

d-=3 # this is same as d=d-3
print(d)


# comparison operators

print(a==b) # this will print false because a is not equal to b
print(a!=b) # this will print true because a is not equal to b
d=9==3*3
print(d) # this will print true because 9 is equal to 3*3

e=5>3
print(e) # this will print true because 5 is greater than 3


# logical operators

l=True or False
print(l) # this will print true because at least one of the operands is true

m=True and False
print(m) # this will print false because both operands are not true

print(not(True)) # this will print false because not operator negates the value of true
